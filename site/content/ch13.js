双缝是“两个源”，单缝是“无穷多个源”。数学上，双缝的光程差只取两个离散值，求和是两项相加；单缝要对连续分布求积分（半波带法就是它的离散近似）。因此双缝给出一串等间距的亮线，单缝给出一个又宽又亮的中央斑。

