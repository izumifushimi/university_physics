质心运动定理的右端只有外力。这解释了一个反直觉的事实：炮弹在空中爆炸，碎片飞得再乱，它们的质心仍沿原来的抛物线前进；两个滑冰者互相推开，无论推得多用力，两人的质心保持原来的运动状态。

