这一步比第一步更重要。**方法选错通常还能算出个数，条件用错则一定错。**

- 动量守恒要求合外力为零，或某方向分量为零，或过程极短使外力冲量可忽略。碰撞、爆炸满足最后一条；沿粗糙面缓慢滑动不满足。
